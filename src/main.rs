/// Bits permutataion
///
/// ```ignore
/// (((v >> 0) & 1) << arr[0]) | (((v >> 1) & 1) << arr[2]) | ...
/// ```
#[macro_export]
macro_rules! bit_permutation {
    ($v: ident, $pos:expr, [$next:literal]) => {
        (($v >> $pos) & 1) << $next
    };

    ($v: ident, $pos:expr, [$next:literal, $($arr:literal),+ $(,)?]) => {
        bit_permutation!($v, $pos, [$next]) | bit_permutation!($v, $pos + 1, [$($arr),+])
    };

    ($v: ident, [$($arr:literal),+ $(,)?]) => {
        bit_permutation!($v, 0, [$($arr),+])
    };
}
