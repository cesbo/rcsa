typedef struct {
    uint8_t ccw[16];

    // block cypher
    uint8_t kk[56];

    // stream cypher
    uint8_t A[42];
    uint8_t B[42];
    uint8_t X;
    uint8_t Y;
    uint8_t Z;
    uint8_t D;
    uint8_t E;
    uint8_t F;
    uint8_t r;
    uint8_t p;
    uint8_t q;
} csa_ctx_t;

#define BB_00 0x00
#define BB_01 0x01
#define BB_0F 0x0F
#define BB_FF 0xFF

#define BB_AND(A, B) ((A) & (B))
#define BB_OR(A, B) ((A) | (B))
#define BB_XOR(A, B) ((A) ^ (B))
#define BB_LSH(A, B) ((A) << (B))
#define BB_RSH(A, B) ((A) >> (B))

#define BIT_LSH(V, S) BB_LSH(BB_AND(V, BB_01), S)

#define A_GROUP(V1, V2, V3, V4, V5)                 \
    BB_OR(BIT_LSH(V1, 4),                           \
    BB_OR(BIT_LSH(V2, 3),                           \
    BB_OR(BIT_LSH(V3, 2),                           \
    BB_OR(BIT_LSH(V4, 1),                           \
          BB_AND(V5, BB_01)))))

#define B_GROUP(S, V1, V2, V3, V4)                  \
    BB_XOR(BIT_LSH(V1, S),                          \
    BB_XOR(BIT_LSH(V2, S),                          \
    BB_XOR(BIT_LSH(V3, S),                          \
           BIT_LSH(V4, S))))

#define S_GROUP(V1, V2, V3, V4)                     \
    BB_OR(BIT_LSH(V1, 3),                           \
    BB_OR(BIT_LSH(V2, 2),                           \
    BB_OR(BIT_LSH(BB_AND(BB_RSH(V3, 1), BB_01), 1), \
          BB_AND(BB_RSH(V4, 1), BB_01))))

static uint8_t sbox1[0x20] = {2,0,1,1,2,3,3,0, 3,2,2,0,1,1,0,3, 0,3,3,0,2,2,1,1, 2,2,0,3,1,1,3,0};
static uint8_t sbox2[0x20] = {3,1,0,2,2,3,3,0, 1,3,2,1,0,0,1,2, 3,1,0,3,3,2,0,2, 0,0,1,2,2,1,3,1};
static uint8_t sbox3[0x20] = {2,0,1,2,2,3,3,1, 1,1,0,3,3,0,2,0, 1,3,0,1,3,0,2,2, 2,0,1,2,0,3,3,1};
static uint8_t sbox4[0x20] = {3,1,2,3,0,2,1,2, 1,2,0,1,3,0,0,3, 1,0,3,1,2,3,0,3, 0,3,2,0,1,2,2,1};
static uint8_t sbox5[0x20] = {2,0,0,1,3,2,3,2, 0,1,3,3,1,0,2,1, 2,3,2,0,0,3,1,1, 1,0,3,2,3,1,0,2};
static uint8_t sbox6[0x20] = {0,1,2,3,1,2,2,0, 0,1,3,0,2,3,1,3, 2,3,0,2,3,0,1,1, 2,1,1,2,0,3,3,0};
static uint8_t sbox7[0x20] = {0,3,2,2,3,0,0,1, 3,0,1,3,1,2,2,1, 1,0,3,3,0,1,1,2, 2,3,1,0,2,3,0,2};


static void stream_cypher(csa_ctx_t *ctx, uint8_t *sb, uint8_t *cb)
{
    int i,j;
    uint8_t s1,s2,s3,s4,s5,s6,s7;

    if(sb)
    {
        memcpy(cb, sb, 8);

        memcpy(&ctx->A[32], &ctx->ccw[0], 8);
        memcpy(&ctx->B[32], &ctx->ccw[8], 8);

        memset(&ctx->A[40], 0, 2);
        memset(&ctx->B[40], 0, 2);

        for(i = 0, j = 28; i < 8; i += 1, j -= 4)
        {
            s1 = sb[i] >> 4;
            s2 = sb[i] & 0x0F;

            ctx->A[j + 3] = s1;
            ctx->A[j + 2] = s2;

            ctx->A[j + 1] = s1;
            ctx->A[j + 0] = s2;

            ctx->B[j + 2] = s1;
            ctx->B[j + 3] = s2;

            ctx->B[j + 0] = s1;
            ctx->B[j + 1] = s2;
        }

        ctx->X = 0;
        ctx->Y = 0;
        ctx->Z = 0;
        ctx->D = 0;
        ctx->E = 0;
        ctx->F = 0;
        ctx->r = 0;
        ctx->p = 0;
        ctx->q = 0;
    }

    // 8 bytes and 4 bits per operation
    for(i = 0, j = 31; i < 32; i += 1, j -= 1)
    {
        // T1
        ctx->X = ctx->X ^ ctx->A[j + 10];
        ctx->Y = ctx->Y ^ ctx->B[j + 10] ^ ctx->B[j + 7];

        if(sb)
        {
            ctx->A[j] = ctx->X ^ ctx->A[j] ^ ctx->D;
            ctx->B[j] = ctx->Y ^ ctx->B[j];
        }
        else
        {
            ctx->A[j] = ctx->X;
            ctx->B[j] = ctx->Y;
        }

        // if p!=0, rotate left
        if(ctx->p != 0)
            ctx->B[j] = ((ctx->B[j] << 1) | ((ctx->B[j] >> 3) & 1)) & 0x0F;

        // T3
        ctx->D = ctx->E ^ ctx->Z ^ (
            B_GROUP(3, ctx->B[j + 3] >> 0, ctx->B[j + 6] >> 1, ctx->B[j + 7] >> 2, ctx->B[j + 9] >> 3) |
            B_GROUP(2, ctx->B[j + 6] >> 0, ctx->B[j + 8] >> 1, ctx->B[j + 3] >> 3, ctx->B[j + 4] >> 2) |
            B_GROUP(1, ctx->B[j + 5] >> 3, ctx->B[j + 8] >> 2, ctx->B[j + 4] >> 0, ctx->B[j + 5] >> 1) |
            B_GROUP(0, ctx->B[j + 9] >> 2, ctx->B[j + 6] >> 3, ctx->B[j + 3] >> 1, ctx->B[j + 8] >> 0) );

        // T4
        s1 = ctx->F;
        if(ctx->q)
        {
            ctx->F = ctx->E + ctx->Z + ctx->r;
            ctx->r = (ctx->F >> 4) & 1;
        }
        else
        {
            ctx->F = ctx->E;
        }
        ctx->E = s1 & 0x0F;

        // from A[0]..A[9], 35 bits are selected as inputs to 7 s-boxes
        // 5 bits input per s-box, 2 bits output per s-box
        s1 = sbox1[A_GROUP(ctx->A[j + 4] >> 0, ctx->A[j + 1] >> 2, ctx->A[j + 6] >> 1, ctx->A[j + 7] >> 3, ctx->A[j + 9] >> 0)];
        s2 = sbox2[A_GROUP(ctx->A[j + 2] >> 1, ctx->A[j + 3] >> 2, ctx->A[j + 6] >> 3, ctx->A[j + 7] >> 0, ctx->A[j + 9] >> 1)];
        s3 = sbox3[A_GROUP(ctx->A[j + 1] >> 3, ctx->A[j + 2] >> 0, ctx->A[j + 5] >> 1, ctx->A[j + 5] >> 3, ctx->A[j + 6] >> 2)];
        s4 = sbox4[A_GROUP(ctx->A[j + 3] >> 3, ctx->A[j + 1] >> 1, ctx->A[j + 2] >> 3, ctx->A[j + 4] >> 2, ctx->A[j + 8] >> 0)];
        s5 = sbox5[A_GROUP(ctx->A[j + 5] >> 2, ctx->A[j + 4] >> 3, ctx->A[j + 6] >> 0, ctx->A[j + 8] >> 1, ctx->A[j + 9] >> 2)];
        s6 = sbox6[A_GROUP(ctx->A[j + 3] >> 1, ctx->A[j + 4] >> 1, ctx->A[j + 5] >> 0, ctx->A[j + 7] >> 2, ctx->A[j + 9] >> 3)];
        s7 = sbox7[A_GROUP(ctx->A[j + 2] >> 2, ctx->A[j + 3] >> 0, ctx->A[j + 7] >> 1, ctx->A[j + 8] >> 2, ctx->A[j + 8] >> 3)];

        ctx->X = S_GROUP(s4, s3, s2, s1);
        ctx->Y = S_GROUP(s6, s5, s4, s3);
        ctx->Z = S_GROUP(s2, s1, s6, s5);
        ctx->p = s7 & 2;
        ctx->q = s7 & 1;

        // require 4 loops per output byte
        // 2 output bits are a function of the 4 bits of D
        // xor 2 by 2
        if(!sb)
        {
            s1 = ctx->D ^ (ctx->D >> 1);
            s1 = ((s1 >> 1) & 2) | (s1 & 1);
            s2 = i >> 2;

            cb[s2] = (cb[s2] << 2) | s1;
        }

    }

    memcpy(&ctx->A[32], &ctx->A[0], 10);
    memcpy(&ctx->B[32], &ctx->B[0], 10);
}

