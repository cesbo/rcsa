void key_schedule(csa_ctx_t *ctx, uint8_t *cw)
{
    int i,j,k,v;
    uint8_t newbit[64];
    uint8_t kb[64];

    memset(ctx, 0, sizeof(ctx));
    *(uint64_t *)(ctx->cw) = *(uint64_t *)(cw);
    *(uint64_t *)(&kb[56]) = *(uint64_t *)(cw);

    // calculate kb[6] .. kb[1]
    for(i=48; i>=0; i-=8)
    {
        // 64 bit perm on kb
        for(j=0; j<=56; j+=8)
        {
            v = i + (j >> 3);
            v = kb[8 + v];
            for(k=0; k<8; k++)
                newbit[key_perm[j + k] - 1] = (v >> (7 - k)) & 1;
        }

        for(j=0; j<=56; j+=8)
        {
            v = i + (j >> 3);
            kb[v] =
                newbit[j + 0] << 7 |
                newbit[j + 1] << 6 |
                newbit[j + 2] << 5 |
                newbit[j + 3] << 4 |
                newbit[j + 4] << 3 |
                newbit[j + 5] << 2 |
                newbit[j + 6] << 1 |
                newbit[j + 7];
            ctx->kk[v] = kb[8 + v] ^ (i >> 3);
        }
    }
}




void block_decypher(csa_ctx_t *ctx, uint8_t *ib, uint8_t *bd)
{
    int x,i;
    uint8_t sbox_out;
    uint8_t T[64];

    *(uint64_t *)&T[56] = *(uint64_t *)ib;

    for(i=55; i>=0; i--)
    {
        sbox_out = block_sbox[ctx->kk[i] ^ T[i+1+6]];
        T[i+6] ^= block_perm[sbox_out];
        T[i] = T[i+1+7] ^ sbox_out;
        T[i+4] ^= T[i];
        T[i+3] ^= T[i];
        T[i+2] ^= T[i];
    }

    *(uint64_t *)bd = *(uint64_t *)T;
}


void block_encypher(csa_ctx_t *ctx, uint8_t *bd, uint8_t *ib)
{
    int i;
    int sbox_in;
    int sbox_out;
    int perm_out;
    uint8_t R[8];
    uint8_t next_R0;

    *(uint64_t *)R = *(uint64_t *)bd;

    // loop over kk[1]..kk[56]
    for(i=0; i<56; i++)
    {
        sbox_in = ctx->kk[i] ^ R[7];
        sbox_out = block_sbox[sbox_in];
        perm_out = block_perm[sbox_out];

        next_R0 = R[1];
        R[1] = R[2] ^ R[0];
        R[2] = R[3] ^ R[0];
        R[3] = R[4] ^ R[0];
        R[4] = R[5];
        R[5] = R[6] ^ perm_out;
        R[6] = R[7];
        R[7] = R[0] ^ sbox_out;

        R[0] = next_R0;
    }

    *(uint64_t *)ib = *(uint64_t *)R;
}














