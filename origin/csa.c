typedef struct {
    uint8_t ccw[20];

    // block cypher
    uint8_t kk[56];

    // stream cypher
    uint8_t A[10];
    uint8_t B[10];
    uint8_t X;
    uint8_t Y;
    uint8_t Z;
    uint8_t D;
    uint8_t E;
    uint8_t F;
    uint8_t r;
    uint8_t p;
    uint8_t q;
} csa_ctx_t;

#define BB_00 0x00
#define BB_01 0x01
#define BB_0F 0x0F
#define BB_FF 0xFF

#define BB_AND(A, B) ((A) & (B))
#define BB_OR(A, B) ((A) | (B))
#define BB_XOR(A, B) ((A) ^ (B))
#define BB_LSH(A, B) ((A) << (B))
#define BB_RSH(A, B) ((A) >> (B))

#define BIT_LSH(V, S) BB_LSH(BB_AND(V, BB_01), S)

#define A_GROUP(V1, V2, V3, V4, V5)                 \
    BB_OR(BIT_LSH(V1, 4),                           \
    BB_OR(BIT_LSH(V2, 3),                           \
    BB_OR(BIT_LSH(V3, 2),                           \
    BB_OR(BIT_LSH(V4, 1),                           \
          BB_AND(V5, BB_01)))))

#define B_GROUP(S, V1, V2, V3, V4)                  \
    BB_XOR(BIT_LSH(V1, S),                          \
    BB_XOR(BIT_LSH(V2, S),                          \
    BB_XOR(BIT_LSH(V3, S),                          \
           BIT_LSH(V4, S))))

#define S_GROUP(V1, V2, V3, V4)                     \
    BB_OR(BIT_LSH(V1, 3),                           \
    BB_OR(BIT_LSH(V2, 2),                           \
    BB_OR(BIT_LSH(BB_AND(BB_RSH(V3, 1), BB_01), 1), \
          BB_AND(BB_RSH(V4, 1), BB_01))))


static uint8_t sbox1[0x20] = {2,0,1,1,2,3,3,0, 3,2,2,0,1,1,0,3, 0,3,3,0,2,2,1,1, 2,2,0,3,1,1,3,0};
static uint8_t sbox2[0x20] = {3,1,0,2,2,3,3,0, 1,3,2,1,0,0,1,2, 3,1,0,3,3,2,0,2, 0,0,1,2,2,1,3,1};
static uint8_t sbox3[0x20] = {2,0,1,2,2,3,3,1, 1,1,0,3,3,0,2,0, 1,3,0,1,3,0,2,2, 2,0,1,2,0,3,3,1};
static uint8_t sbox4[0x20] = {3,1,2,3,0,2,1,2, 1,2,0,1,3,0,0,3, 1,0,3,1,2,3,0,3, 0,3,2,0,1,2,2,1};
static uint8_t sbox5[0x20] = {2,0,0,1,3,2,3,2, 0,1,3,3,1,0,2,1, 2,3,2,0,0,3,1,1, 1,0,3,2,3,1,0,2};
static uint8_t sbox6[0x20] = {0,1,2,3,1,2,2,0, 0,1,3,0,2,3,1,3, 2,3,0,2,3,0,1,1, 2,1,1,2,0,3,3,0};
static uint8_t sbox7[0x20] = {0,3,2,2,3,0,0,1, 3,0,1,3,1,2,2,1, 1,0,3,3,0,1,1,2, 2,3,1,0,2,3,0,2};


static void stream_cypher(csa_ctx_t *ctx, uint8_t *sb, uint8_t *cb)
{
    int i,j;
    uint8_t tmp,s1,s2,s3,s4,s5,s6,s7;

    int in1 = 0; // most significant nibble of input byte
    int in2 = 0; // least significant nibble of input byte
    int op, extra_B, next_A0, next_B0;
    uint8_t in[16];

    if(sb)
    {
        memcpy(ctx->A, &ctx->ccw[ 0], 10);
        memcpy(ctx->B, &ctx->ccw[10], 10);

        for(i = 0; i < 8; i += 1)
        {
            in[i * 2 + 0] = sb[i] >> 4;
            in[i * 2 + 1] = sb[i] & 0x0F;
        }

        ctx->X = 0;
        ctx->Y = 0;
        ctx->Z = 0;
        ctx->D = 0;
        ctx->E = 0;
        ctx->F = 0;
        ctx->r = 0;
        ctx->p = 0;
        ctx->q = 0;
    }

    // 8 bytes per operation
    for(i = 0; i < 8; i += 1)
    {
        if(sb)
        {
            in1 = in[i * 2 + 0];
            in2 = in[i * 2 + 1];
        }

        op = 0;

        // 2 bits per iteration
        for (j = 0; j < 4; j++)
        {
            // from A[1]..A[10], 35 bits are selected as inputs to 7 s-boxes
            // 5 bits input per s-box, 2 bits output per s-box
            s1 = sbox1[A_GROUP(ctx->A[3] >> 0, ctx->A[0] >> 2, ctx->A[5] >> 1, ctx->A[6] >> 3, ctx->A[8] >> 0)];
            s2 = sbox2[A_GROUP(ctx->A[1] >> 1, ctx->A[2] >> 2, ctx->A[5] >> 3, ctx->A[6] >> 0, ctx->A[8] >> 1)];
            s3 = sbox3[A_GROUP(ctx->A[0] >> 3, ctx->A[1] >> 0, ctx->A[4] >> 1, ctx->A[4] >> 3, ctx->A[5] >> 2)];
            s4 = sbox4[A_GROUP(ctx->A[2] >> 3, ctx->A[0] >> 1, ctx->A[1] >> 3, ctx->A[3] >> 2, ctx->A[7] >> 0)];
            s5 = sbox5[A_GROUP(ctx->A[4] >> 2, ctx->A[3] >> 3, ctx->A[5] >> 0, ctx->A[7] >> 1, ctx->A[8] >> 2)];
            s6 = sbox6[A_GROUP(ctx->A[2] >> 1, ctx->A[3] >> 1, ctx->A[4] >> 0, ctx->A[6] >> 2, ctx->A[8] >> 3)];
            s7 = sbox7[A_GROUP(ctx->A[1] >> 2, ctx->A[2] >> 0, ctx->A[6] >> 1, ctx->A[7] >> 2, ctx->A[7] >> 3)];

            extra_B =
                B_GROUP(3, ctx->B[2] >> 0, ctx->B[5] >> 1, ctx->B[6] >> 2, ctx->B[8] >> 3) |
                B_GROUP(2, ctx->B[5] >> 0, ctx->B[7] >> 1, ctx->B[2] >> 3, ctx->B[3] >> 2) |
                B_GROUP(1, ctx->B[4] >> 3, ctx->B[7] >> 2, ctx->B[3] >> 0, ctx->B[4] >> 1) |
                B_GROUP(0, ctx->B[8] >> 2, ctx->B[5] >> 3, ctx->B[2] >> 1, ctx->B[7] >> 0) ;

            // T1 = xor all inputs
            // in1, in2, D are only used in T1 during initialisation,
            // not generation
            next_A0 = ctx->A[9] ^ ctx->X;
            if(sb)
                next_A0 = next_A0 ^ ctx->D ^ in[i * 2 + (j & 1)];

            // T2 =  xor all inputs
            // in1,in2 are only used in T1 during initialisation, not generation
            // if p=0, use this, if p=1, rotate the result left
            next_B0 = ctx->B[7 - 1] ^ ctx->B[9] ^ ctx->Y;
            if(sb)
                next_B0 = next_B0 ^ in[i * 2 + 1 - (j & 1)];

            // if p != 0, rotate left
            if(ctx->p != 0)
                next_B0 = (next_B0 << 1) | ((next_B0 >> 3) & 1);

            // T3 = xor all inputs
            ctx->D = ctx->E ^ ctx->Z ^ extra_B;

            // T4 = sum, carry of Z + E + r
            tmp = ctx->F;
            if(ctx->q)
            {
                ctx->F = ctx->Z + ctx->E + ctx->r;
                ctx->r = (ctx->F >> 4) & 1;
                ctx->F = ctx->F & 0x0F;
            }
            else
            {
                ctx->F = ctx->E;
            }
            ctx->E = tmp;

            ctx->A[9]  = ctx->A[8];
            ctx->A[8]  = ctx->A[7];
            ctx->A[7]  = ctx->A[6];
            ctx->A[6]  = ctx->A[5];
            ctx->A[5]  = ctx->A[4];
            ctx->A[4]  = ctx->A[3];
            ctx->A[3]  = ctx->A[2];
            ctx->A[2]  = ctx->A[1];
            ctx->A[1]  = ctx->A[0];
            ctx->A[0]  = next_A0;

            ctx->B[9]  = ctx->B[8];
            ctx->B[8]  = ctx->B[7];
            ctx->B[7]  = ctx->B[6];
            ctx->B[6]  = ctx->B[5];
            ctx->B[5]  = ctx->B[4];
            ctx->B[4]  = ctx->B[3];
            ctx->B[3]  = ctx->B[2];
            ctx->B[2]  = ctx->B[1];
            ctx->B[1]  = ctx->B[0];
            ctx->B[0]  = next_B0;

            ctx->X = S_GROUP(s4, s3, s2, s1);
            ctx->Y = S_GROUP(s6, s5, s4, s3);
            ctx->Z = S_GROUP(s2, s1, s6, s5);
            ctx->p = s7 & 2;
            ctx->q = s7 & 1;

            // require 4 loops per output byte
            // 2 output bits are a function of the 4 bits of D
            // xor 2 by 2
            tmp = ctx->D ^ (ctx->D >> 1);
            tmp = ((tmp >> 1) & 2) | (tmp & 1);
            op = (op << 2) | tmp;
        }

        cb[i] = (sb) ? sb[i] : op;
    }
}


