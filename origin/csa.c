void key_schedule(csa_ctx_t *ctx, uint8_t *cw) {
    int i, j, k, v;
    uint8_t newbit[64];
    uint8_t kb[64];

    // load first 32 bits of CK into A[0]..A[7]
    // load last  32 bits of CK into B[0]..B[7]
    // all other regs = 0
    for(i=0; i<8; i++) {
        kb[56 + i] = cw[i];
    }

    ctx->ccw[0] = cw[0] >> 4;
    ctx->ccw[1] = cw[0] & 0x0F;
    ctx->ccw[2] = cw[1] >> 4;
    ctx->ccw[3] = cw[1] & 0x0F;
    ctx->ccw[4] = cw[2] >> 4;
    ctx->ccw[5] = cw[2] & 0x0F;
    ctx->ccw[6] = cw[3] >> 4;
    ctx->ccw[7] = cw[3] & 0x0F;
    ctx->ccw[8] = 0;
    ctx->ccw[9] = 0;

    ctx->ccw[10] = cw[4] >> 4;
    ctx->ccw[11] = cw[4] & 0x0F;
    ctx->ccw[12] = cw[5] >> 4;
    ctx->ccw[13] = cw[5] & 0x0F;
    ctx->ccw[14] = cw[6] >> 4;
    ctx->ccw[15] = cw[6] & 0x0F;
    ctx->ccw[16] = cw[7] >> 4;
    ctx->ccw[17] = cw[7] & 0x0F;
    ctx->ccw[18] = 0;
    ctx->ccw[19] = 0;


    // calculate kb[6] .. kb[1]
    for(i=48; i>=0; i-=8)
    {
        // 64 bit perm on kb
        for(j=0; j<=56; j+=8)
        {
            v = kb[8 + i + (j >> 3)];
            newbit[key_perm[j + 0]] = (v >> 7) & 1;
            newbit[key_perm[j + 1]] = (v >> 6) & 1;
            newbit[key_perm[j + 2]] = (v >> 5) & 1;
            newbit[key_perm[j + 3]] = (v >> 4) & 1;
            newbit[key_perm[j + 4]] = (v >> 3) & 1;
            newbit[key_perm[j + 5]] = (v >> 2) & 1;
            newbit[key_perm[j + 6]] = (v >> 1) & 1;
            newbit[key_perm[j + 7]] = (v     ) & 1;
        }

        for(j=0; j<=56; j+=8)
        {
            v = i + (j >> 3);
            kb[v] =
                newbit[j + 0] << 7 |
                newbit[j + 1] << 6 |
                newbit[j + 2] << 5 |
                newbit[j + 3] << 4 |
                newbit[j + 4] << 3 |
                newbit[j + 5] << 2 |
                newbit[j + 6] << 1 |
                newbit[j + 7]      ;
            ctx->kk[v] = kb[8 + v] ^ (i >> 3);
        }
    }
}


