void key_schedule(csa_ctx_t *ctx, uint8_t *cw) {
    int i, j, k, v;
    uint8_t newbit[64];
    uint8_t kb[64];

    // load first 32 bits of CK into A[0]..A[7]
    // load last  32 bits of CK into B[0]..B[7]
    // all other regs = 0
    for(i=0; i<8; i++) {
        kb[56 + i] = cw[i];
        ctx->ccw[i * 2 + 0] = cw[i] >> 4;
        ctx->ccw[i * 2 + 1] = cw[i] & 0x0F;
    }

    // calculate kb[6] .. kb[1]
    for(i=48; i>=0; i-=8)
    {
        // 64 bit perm on kb
        for(j=0; j<=56; j+=8)
        {
            v = kb[8 + i + (j >> 3)];
            newbit[key_perm[j + 0]] = (v >> 7) & 1;
            newbit[key_perm[j + 1]] = (v >> 6) & 1;
            newbit[key_perm[j + 2]] = (v >> 5) & 1;
            newbit[key_perm[j + 3]] = (v >> 4) & 1;
            newbit[key_perm[j + 4]] = (v >> 3) & 1;
            newbit[key_perm[j + 5]] = (v >> 2) & 1;
            newbit[key_perm[j + 6]] = (v >> 1) & 1;
            newbit[key_perm[j + 7]] = (v     ) & 1;
        }

        for(j=0; j<=56; j+=8)
        {
            v = i + (j >> 3);
            kb[v] =
                newbit[j + 0] << 7 |
                newbit[j + 1] << 6 |
                newbit[j + 2] << 5 |
                newbit[j + 3] << 4 |
                newbit[j + 4] << 3 |
                newbit[j + 5] << 2 |
                newbit[j + 6] << 1 |
                newbit[j + 7]      ;
            ctx->kk[v] = kb[8 + v] ^ (i >> 3);
        }
    }
}


static void block_decypher(csa_ctx_t *ctx, uint8_t *ib, uint8_t *bd)
{
    int i;
    uint8_t sbox_out;

    memcpy(bd, ib, 8);

    for(i = 55; i >= 0; i -= 1)
    {
        sbox_out = block_sbox[ctx->kk[i] ^ bd[6]];
        bd[5] ^= block_perm[sbox_out];
        sbox_out ^= bd[7];

        bd[7] = bd[6];
        bd[6] = bd[5];
        bd[5] = bd[4];
        bd[4] = bd[3] ^ sbox_out;
        bd[3] = bd[2] ^ sbox_out;
        bd[2] = bd[1] ^ sbox_out;
        bd[1] = bd[0];
        bd[0] = sbox_out;
    }
}

