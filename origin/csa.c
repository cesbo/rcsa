static void block_decypher(csa_ctx_t *ctx, uint8_t *ib, uint8_t *bd)
{
    int i;
    uint8_t sbox_out;

    memcpy(bd, ib, 8);

    for(i = 55; i >= 0; i -= 1)
    {
        sbox_out = block_sbox[ctx->kk[i] ^ bd[6]];
        bd[5] ^= block_perm[sbox_out];
        sbox_out ^= bd[7];

        bd[7] = bd[6];
        bd[6] = bd[5];
        bd[5] = bd[4];
        bd[4] = bd[3] ^ sbox_out;
        bd[3] = bd[2] ^ sbox_out;
        bd[2] = bd[1] ^ sbox_out;
        bd[1] = bd[0];
        bd[0] = sbox_out;
    }
}


